//! Worlds on Vulkan: the pass that draws a world frame into its target,
//! before the 2D pass composites the target into the scene.
//!
//! The frame is the core's (`bunny_ui::world::frame`): which draws, in
//! which order, with which instances and lights. This module only moves
//! its bytes and records its draws. The shaders are the GL family's
//! (`bunny_ui::gpu::world_shaders`) in the Vulkan dialect: [`sources`]
//! makes each stage whole, the files under `src/shaders/world_*` are
//! what it wrote, and a test holds the two together — so the shading
//! has one text for every GL-family tier, and the oracle's parity tests
//! hold it.
//!
//! A target is an RGBA8 image the 2D pass samples. With four samples
//! the drawing goes to a transient multisample image that the render
//! pass resolves into it; the depth is a transient 32-bit float image.
//! The render pass leaves the picture ready to be sampled, and its
//! dependencies order it against the 2D pass that reads it.
//!
//! A frame whose sun casts draws its casters first, when the box's map
//! does not hold them yet: a render pass of depth alone into a 16-bit map
//! (set 2) the surfaces read through a comparing sampler. A frame without
//! a map binds a texel and a sampler whose comparison always passes.
//!
//! Vulkan keeps no reference to what a recorded frame reads: whatever
//! the walk gives back is destroyed only once every frame in flight has
//! come back ([`VkWorld::sweep`]).
//!
//! The world's pipelines and shader modules are made the first time a
//! box paints a world: an app that shows none never pays for them.

