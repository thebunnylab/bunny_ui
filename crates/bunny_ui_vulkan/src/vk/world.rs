/// The world door a walk opens: the world, and the stack it builds with.
pub(super) struct VkWorldDoor<'a> {
    pub(super) stack: &'a VkStack,
    pub(super) world: &'a mut VkWorld,
}

impl VkWorldDoor<'_> {
    /// The door, once the pass stands: built on the first ask, and never
    /// asked again when it failed.
    pub(super) fn open(&mut self) -> Option<&mut dyn WorldGround> {
        if let Built::Not = self.world.built {
            self.world.built = match unsafe { WorldStack::build(self.stack) } {
                Ok(stack) => Built::Ready(Box::new(stack)),
                Err(reason) => {
                    eprintln!("bunny_ui vk: {reason} — worlds draw on the cpu");
                    Built::Failed
                }
            };
        }
        match self.world.built {
            Built::Ready(_) => Some(self),
            _ => None,
        }
    }
}

