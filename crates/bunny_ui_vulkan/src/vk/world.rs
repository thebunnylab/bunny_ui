/// The casters' pass: a 16-bit depth cleared to the far plane, kept, and
/// left ready to be sampled. Its dependencies order it after the frames
/// that read the same map and before the world pass that reads it now.
unsafe fn shadow_pass(stack: &VkStack) -> Result<RenderPass, String> {
    let depth = AttachmentDescription {
        flags: 0,
        format: FORMAT_D16_UNORM,
        samples: SAMPLE_COUNT_1,
        load_op: ATTACHMENT_LOAD_CLEAR,
        store_op: ATTACHMENT_STORE_STORE,
        stencil_load: ATTACHMENT_LOAD_DONT_CARE,
        stencil_store: ATTACHMENT_STORE_DONT_CARE,
        initial_layout: IMAGE_LAYOUT_UNDEFINED,
        final_layout: IMAGE_LAYOUT_SHADER_READ_ONLY,
    };
    let depth_reference = AttachmentReference { attachment: 0, layout: IMAGE_LAYOUT_DEPTH_ATTACHMENT };
    let subpass = SubpassDescription {
        flags: 0,
        bind_point: PIPELINE_BIND_POINT_GRAPHICS,
        input_count: 0,
        inputs: std::ptr::null(),
        color_count: 0,
        colors: std::ptr::null(),
        resolves: std::ptr::null(),
        depth: &depth_reference,
        preserve_count: 0,
        preserves: std::ptr::null(),
    };
    let tests = PIPELINE_STAGE_EARLY_FRAGMENT_TESTS | PIPELINE_STAGE_LATE_FRAGMENT_TESTS;
    let dependencies = [
        SubpassDependency {
            src_subpass: SUBPASS_EXTERNAL,
            dst_subpass: 0,
            src_stage: PIPELINE_STAGE_FRAGMENT_SHADER | tests,
            dst_stage: tests,
            src_access: ACCESS_DEPTH_ATTACHMENT_WRITE,
            dst_access: ACCESS_DEPTH_ATTACHMENT_READ | ACCESS_DEPTH_ATTACHMENT_WRITE,
            flags: 0,
        },
        SubpassDependency {
            src_subpass: 0,
            dst_subpass: SUBPASS_EXTERNAL,
            src_stage: tests,
            dst_stage: PIPELINE_STAGE_FRAGMENT_SHADER,
            src_access: ACCESS_DEPTH_ATTACHMENT_WRITE,
            dst_access: ACCESS_SHADER_READ,
            flags: 0,
        },
    ];
    let info = RenderPassCreateInfo {
        s_type: ST_RENDER_PASS_CREATE,
        p_next: std::ptr::null(),
        flags: 0,
        attachment_count: 1,
        attachments: &depth,
        subpass_count: 1,
        subpasses: &subpass,
        dependency_count: 2,
        dependencies: dependencies.as_ptr().cast(),
    };
    let mut pass: RenderPass = 0;
    unsafe {
        if !ok((stack.fns.create_render_pass)(stack.device, &info, std::ptr::null(), &mut pass)) {
            return Err("the shadow render pass refused".into());
        }
    }
    Ok(pass)
}

/// The render pass of a world at `samples`: colour and depth cleared,
/// the picture left ready to be sampled — resolved from four samples, or
/// drawn straight at one. Its dependencies order it after the frames
/// that sampled or drew the same target, and before the 2D pass that
/// samples it now (or a copy out).
unsafe fn world_pass(stack: &VkStack, samples: u8) -> Result<RenderPass, String> {
    let count = if samples > 1 { SAMPLE_COUNT_4 } else { SAMPLE_COUNT_1 };
    let color = AttachmentDescription {
        flags: 0,
        format: FORMAT_R8G8B8A8_UNORM,
        samples: count,
        load_op: ATTACHMENT_LOAD_CLEAR,
        store_op: if samples > 1 { ATTACHMENT_STORE_DONT_CARE } else { ATTACHMENT_STORE_STORE },
        stencil_load: ATTACHMENT_LOAD_DONT_CARE,
        stencil_store: ATTACHMENT_STORE_DONT_CARE,
        initial_layout: IMAGE_LAYOUT_UNDEFINED,
        final_layout: if samples > 1 { IMAGE_LAYOUT_COLOR_ATTACHMENT } else { IMAGE_LAYOUT_SHADER_READ_ONLY },
    };
    let depth = AttachmentDescription {
        flags: 0,
        format: FORMAT_D32_SFLOAT,
        samples: count,
        load_op: ATTACHMENT_LOAD_CLEAR,
        store_op: ATTACHMENT_STORE_DONT_CARE,
        stencil_load: ATTACHMENT_LOAD_DONT_CARE,
        stencil_store: ATTACHMENT_STORE_DONT_CARE,
        initial_layout: IMAGE_LAYOUT_UNDEFINED,
        final_layout: IMAGE_LAYOUT_DEPTH_ATTACHMENT,
    };
    let resolve = AttachmentDescription {
        flags: 0,
        format: FORMAT_R8G8B8A8_UNORM,
        samples: SAMPLE_COUNT_1,
        load_op: ATTACHMENT_LOAD_DONT_CARE,
        store_op: ATTACHMENT_STORE_STORE,
        stencil_load: ATTACHMENT_LOAD_DONT_CARE,
        stencil_store: ATTACHMENT_STORE_DONT_CARE,
        initial_layout: IMAGE_LAYOUT_UNDEFINED,
        final_layout: IMAGE_LAYOUT_SHADER_READ_ONLY,
    };
    let attachments = [color, depth, resolve];
    let color_reference = AttachmentReference { attachment: 0, layout: IMAGE_LAYOUT_COLOR_ATTACHMENT };
    let depth_reference = AttachmentReference { attachment: 1, layout: IMAGE_LAYOUT_DEPTH_ATTACHMENT };
    let resolve_reference = AttachmentReference { attachment: 2, layout: IMAGE_LAYOUT_COLOR_ATTACHMENT };
    let subpass = SubpassDescription {
        flags: 0,
        bind_point: PIPELINE_BIND_POINT_GRAPHICS,
        input_count: 0,
        inputs: std::ptr::null(),
        color_count: 1,
        colors: &color_reference,
        resolves: if samples > 1 { &resolve_reference } else { std::ptr::null() },
        depth: &depth_reference,
        preserve_count: 0,
        preserves: std::ptr::null(),
    };
    let tests = PIPELINE_STAGE_EARLY_FRAGMENT_TESTS | PIPELINE_STAGE_LATE_FRAGMENT_TESTS;
    let dependencies = [
        SubpassDependency {
            src_subpass: SUBPASS_EXTERNAL,
            dst_subpass: 0,
            src_stage: PIPELINE_STAGE_FRAGMENT_SHADER | PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT | PIPELINE_STAGE_TRANSFER | tests,
            dst_stage: PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT | tests,
            src_access: ACCESS_COLOR_ATTACHMENT_WRITE | ACCESS_DEPTH_ATTACHMENT_WRITE,
            dst_access: ACCESS_COLOR_ATTACHMENT_READ
                | ACCESS_COLOR_ATTACHMENT_WRITE
                | ACCESS_DEPTH_ATTACHMENT_READ
                | ACCESS_DEPTH_ATTACHMENT_WRITE,
            flags: 0,
        },
        SubpassDependency {
            src_subpass: 0,
            dst_subpass: SUBPASS_EXTERNAL,
            src_stage: PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT,
            dst_stage: PIPELINE_STAGE_FRAGMENT_SHADER | PIPELINE_STAGE_TRANSFER,
            src_access: ACCESS_COLOR_ATTACHMENT_WRITE,
            dst_access: ACCESS_SHADER_READ | ACCESS_TRANSFER_READ,
            flags: 0,
        },
    ];
    let info = RenderPassCreateInfo {
        s_type: ST_RENDER_PASS_CREATE,
        p_next: std::ptr::null(),
        flags: 0,
        attachment_count: if samples > 1 { 3 } else { 2 },
        attachments: attachments.as_ptr(),
        subpass_count: 1,
        subpasses: &subpass,
        dependency_count: 2,
        dependencies: dependencies.as_ptr().cast(),
    };
    let mut pass: RenderPass = 0;
    unsafe {
        if !ok((stack.fns.create_render_pass)(stack.device, &info, std::ptr::null(), &mut pass)) {
            return Err(format!("the world render pass at {samples} samples refused"));
        }
    }
    Ok(pass)
}

/// An image with its memory and a view over all its levels.
#[allow(clippy::too_many_arguments)]
unsafe fn image(
    stack: &VkStack,
    width: u32,
    height: u32,
    format: u32,
    levels: u32,
    samples: u8,
    usage: u32,
    aspect: u32,
    transient: bool,
) -> Option<Image> {
    let fns = &stack.fns;
    unsafe {
        let info = ImageCreateInfo {
            s_type: ST_IMAGE_CREATE,
            p_next: std::ptr::null(),
            flags: 0,
            image_type: IMAGE_TYPE_2D,
            format,
            extent: [width, height, 1],
            mip_levels: levels,
            array_layers: 1,
            samples: if samples > 1 { SAMPLE_COUNT_4 } else { SAMPLE_COUNT_1 },
            tiling: IMAGE_TILING_OPTIMAL,
            usage,
            sharing: SHARING_MODE_EXCLUSIVE,
            family_count: 0,
            families: std::ptr::null(),
            initial_layout: IMAGE_LAYOUT_UNDEFINED,
        };
        let mut handle: ImageHandle = 0;
        if !ok((fns.create_image)(stack.device, &info, std::ptr::null(), &mut handle)) {
            return None;
        }
        let mut requirements = std::mem::zeroed::<MemoryRequirements>();
        (fns.get_image_memory_requirements)(stack.device, handle, &mut requirements);
        // a transient attachment lives in tile memory where the device
        // has it; elsewhere, device memory as any image
        let bits = requirements.memory_type_bits;
        let memory_type = transient
            .then(|| find_memory_type(&stack.memory, bits, MEMORY_PROPERTY_LAZILY_ALLOCATED))
            .flatten()
            .or_else(|| find_memory_type(&stack.memory, bits, MEMORY_PROPERTY_DEVICE_LOCAL))
            .or_else(|| find_memory_type(&stack.memory, bits, 0));
        let Some(memory_type) = memory_type else {
            (fns.destroy_image)(stack.device, handle, std::ptr::null());
            return None;
        };
        let allocate = MemoryAllocateInfo { s_type: ST_MEMORY_ALLOCATE, p_next: std::ptr::null(), size: requirements.size, memory_type };
        let mut memory: DeviceMemory = 0;
        if !ok((fns.allocate_memory)(stack.device, &allocate, std::ptr::null(), &mut memory)) {
            (fns.destroy_image)(stack.device, handle, std::ptr::null());
            return None;
        }
        (fns.bind_image_memory)(stack.device, handle, memory, 0);
        let view_info = ImageViewCreateInfo {
            s_type: ST_IMAGE_VIEW_CREATE,
            p_next: std::ptr::null(),
            flags: 0,
            image: handle,
            view_type: IMAGE_VIEW_TYPE_2D,
            format,
            components: [0; 4],
            aspect,
            base_mip: 0,
            mip_count: levels,
            base_layer: 0,
            layer_count: 1,
        };
        let mut view: ImageView = 0;
        if !ok((fns.create_image_view)(stack.device, &view_info, std::ptr::null(), &mut view)) {
            (fns.destroy_image)(stack.device, handle, std::ptr::null());
            (fns.free_memory)(stack.device, memory, std::ptr::null());
            return None;
        }
        Some(Image { image: handle, memory, view })
    }
}

unsafe fn destroy_image(stack: &VkStack, image: Image) {
    unsafe {
        (stack.fns.destroy_image_view)(stack.device, image.view, std::ptr::null());
        (stack.fns.destroy_image)(stack.device, image.image, std::ptr::null());
        (stack.fns.free_memory)(stack.device, image.memory, std::ptr::null());
    }
}

unsafe fn destroy_buffer(stack: &VkStack, buffer: Buffer) {
    unsafe {
        (stack.fns.destroy_buffer)(stack.device, buffer.buffer, std::ptr::null());
        (stack.fns.free_memory)(stack.device, buffer.memory, std::ptr::null());
    }
}

/// A buffer the GPU reads, written once from the host.
fn filled(stack: &VkStack, bytes: &[u8], usage: u32) -> Option<Buffer> {
    let (buffer, memory, map) = stack.buffer(bytes.len() as u64, usage, MEMORY_PROPERTY_HOST_VISIBLE | MEMORY_PROPERTY_HOST_COHERENT)?;
    unsafe { std::ptr::copy_nonoverlapping(bytes.as_ptr(), map, bytes.len()) };
    Some(Buffer { buffer, memory })
}

/// Records `work` into a command buffer of its own, submits it and waits
/// for it — for the uploads a frame cannot wait to carry.
unsafe fn one_time(stack: &VkStack, work: impl FnOnce(CommandBuffer)) -> bool {
    let fns = &stack.fns;
    unsafe {
        let allocate = CommandBufferAllocateInfo {
            s_type: ST_COMMAND_BUFFER_ALLOCATE,
            p_next: std::ptr::null(),
            pool: stack.command_pool,
            level: COMMAND_BUFFER_LEVEL_PRIMARY,
            count: 1,
        };
        let mut command: CommandBuffer = std::ptr::null_mut();
        if !ok((fns.allocate_command_buffers)(stack.device, &allocate, &mut command)) {
            return false;
        }
        let begin = CommandBufferBeginInfo {
            s_type: ST_COMMAND_BUFFER_BEGIN,
            p_next: std::ptr::null(),
            flags: COMMAND_BUFFER_USAGE_ONE_TIME,
            inheritance: std::ptr::null(),
        };
        (fns.begin_command_buffer)(command, &begin);
        work(command);
        (fns.end_command_buffer)(command);
        let submit = SubmitInfo {
            s_type: ST_SUBMIT_INFO,
            p_next: std::ptr::null(),
            wait_count: 0,
            wait_semaphores: std::ptr::null(),
            wait_stages: std::ptr::null(),
            command_buffer_count: 1,
            command_buffers: &command,
            signal_count: 0,
            signal_semaphores: std::ptr::null(),
        };
        let done = ok((fns.queue_submit)(stack.queue, 1, &submit, 0)) && ok((fns.queue_wait_idle)(stack.queue));
        (fns.free_command_buffers)(stack.device, stack.command_pool, 1, &command);
        done
    }
}

impl WorldGround for VkWorldDoor<'_> {
    fn world_caps(&self) -> WorldCaps {
        WorldCaps { samples: 4 }
    }

    fn make_target(&mut self, width: u32, height: u32, samples: u8) -> Option<u64> {
        let stack = self.stack;
        let Built::Ready(world) = &self.world.built else { return None };
        if width == 0 || height == 0 {
            return None;
        }
        let samples = if samples > 1 { 4 } else { 1 };
        unsafe {
            let picture = image(
                stack,
                width,
                height,
                FORMAT_R8G8B8A8_UNORM,
                1,
                1,
                IMAGE_USAGE_COLOR_ATTACHMENT | IMAGE_USAGE_SAMPLED | IMAGE_USAGE_TRANSFER_SRC,
                IMAGE_ASPECT_COLOR,
                false,
            )?;
            let transient = IMAGE_USAGE_TRANSIENT_ATTACHMENT;
            let color = if samples > 1 {
                match image(stack, width, height, FORMAT_R8G8B8A8_UNORM, 1, samples, IMAGE_USAGE_COLOR_ATTACHMENT | transient, IMAGE_ASPECT_COLOR, true) {
                    Some(color) => Some(color),
                    None => {
                        destroy_image(stack, picture);
                        return None;
                    }
                }
            } else {
                None
            };
            let Some(depth) = image(stack, width, height, FORMAT_D32_SFLOAT, 1, samples, IMAGE_USAGE_DEPTH_STENCIL_ATTACHMENT | transient, IMAGE_ASPECT_DEPTH, true) else {
                destroy_image(stack, picture);
                if let Some(color) = color {
                    destroy_image(stack, color);
                }
                return None;
            };
            let views: Vec<ImageView> = match &color {
                Some(color) => vec![color.view, depth.view, picture.view],
                None => vec![picture.view, depth.view],
            };
            let info = FramebufferCreateInfo {
                s_type: ST_FRAMEBUFFER_CREATE,
                p_next: std::ptr::null(),
                flags: 0,
                render_pass: world.passes[(samples > 1) as usize],
                attachment_count: views.len() as u32,
                attachments: views.as_ptr(),
                width,
                height,
                layers: 1,
            };
            let mut framebuffer: Framebuffer = 0;
            let made = ok((stack.fns.create_framebuffer)(stack.device, &info, std::ptr::null(), &mut framebuffer));
            let set = if made { stack.sampled_set(picture.view, stack.linear_sampler) } else { None };
            let Some(set) = set else {
                if made {
                    (stack.fns.destroy_framebuffer)(stack.device, framebuffer, std::ptr::null());
                }
                for image in [Some(picture), color, Some(depth)].into_iter().flatten() {
                    destroy_image(stack, image);
                }
                return None;
            };
            let target = Target { picture, set, color, depth, framebuffer, size: (width, height), samples };
            let id = self.world.mint();
            self.world.targets.insert(id, target);
            Some(id)
        }
    }

    fn drop_target(&mut self, id: u64) {
        if let Some(target) = self.world.targets.remove(&id) {
            let frame = self.world.frame;
            self.world.graveyard.push((frame, Garbage::Target(target)));
        }
    }

    fn make_mesh(&mut self, vertices: &[u8], indices: &[u8]) -> Option<u64> {
        if vertices.is_empty() || indices.is_empty() {
            return None;
        }
        let vertices = filled(self.stack, vertices, BUFFER_USAGE_VERTEX)?;
        let Some(indices) = filled(self.stack, indices, BUFFER_USAGE_INDEX) else {
            unsafe { destroy_buffer(self.stack, vertices) };
            return None;
        };
        let id = self.world.mint();
        self.world.meshes.insert(id, MeshBuffers { vertices, indices });
        Some(id)
    }

    fn drop_mesh(&mut self, id: u64) {
        if let Some(mesh) = self.world.meshes.remove(&id) {
            let frame = self.world.frame;
            self.world.graveyard.push((frame, Garbage::Mesh(mesh)));
        }
    }

    fn make_texture(&mut self, width: u32, height: u32, levels: &[&[u8]]) -> Option<u64> {
        let Built::Ready(world) = &self.world.built else { return None };
        if levels.is_empty() || width == 0 || height == 0 {
            return None;
        }
        let surface = unsafe { world.surface(self.stack, width, height, levels)? };
        let id = self.world.mint();
        self.world.surfaces.insert(id, surface);
        Some(id)
    }

    fn drop_texture(&mut self, id: u64) {
        if let Some(surface) = self.world.surfaces.remove(&id) {
            let frame = self.world.frame;
            self.world.graveyard.push((frame, Garbage::Surface(surface)));
        }
    }

    fn make_segments(&mut self, segments: &[u8]) -> Option<u64> {
        let count = (segments.len() / SEGMENT_STRIDE) as u32;
        let buffer = if count == 0 { None } else { Some(filled(self.stack, &segments[..count as usize * SEGMENT_STRIDE], BUFFER_USAGE_VERTEX)?) };
        let id = self.world.mint();
        self.world.segments.insert(id, Segments { buffer, count });
        Some(id)
    }

    fn drop_segments(&mut self, id: u64) {
        if let Some(Segments { buffer: Some(buffer), .. }) = self.world.segments.remove(&id) {
            let frame = self.world.frame;
            self.world.graveyard.push((frame, Garbage::Segments(buffer)));
        }
    }

    fn make_shadow_map(&mut self, size: u32) -> Option<u64> {
        let Built::Ready(world) = &self.world.built else { return None };
        let map = unsafe { world.shadow_map(self.stack, size)? };
        let id = self.world.mint();
        self.world.shadow_maps.insert(id, map);
        Some(id)
    }

    fn drop_shadow_map(&mut self, id: u64) {
        if let Some(map) = self.world.shadow_maps.remove(&id) {
            let frame = self.world.frame;
            self.world.graveyard.push((frame, Garbage::Shadow(map)));
        }
    }
}

